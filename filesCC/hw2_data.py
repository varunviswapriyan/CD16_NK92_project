#Training data size
N = len(y_train)
#Number of dimensions in input
d = len(x_train[0])

num_spam = 0
num_notSpam = 0

mean_spam = np.zeros(d)
mean_notSpam = np.zeros(d)

#Looping through training set
for i in range(N):
    if y_train[i] ==1:
        #Updating spam count and mean vector for spam cases, if training case has a label of 1
        num_spam +=1
        mean_spam = mean_spam + x_train[i]
    else:
        #Updating not_spam count and mean vector for not_spam cases, if training case has a label of 0
        num_notSpam +=1
        mean_notSpam = mean_notSpam + x_train[i]

#Creating mean vectors for spam cases and not_spam cases by dividing by total num of spam cases and non spam cases
mean_spam = mean_spam/num_spam
mean_notSpam = mean_notSpam/num_notSpam

#Probabiltiy of spam is number of spam cases in training set divided by training set size
prob_spam = num_spam/N

covariance_matrix = np.zeros((d,d))

#Looping through all training cases
for i in range(N):

    #Getting difference between the input vector x_i and the mean vector corresponding to its label
    if y_train[i]==1:
        temp = x_train[i] - mean_spam
    else:
        temp = x_train[i] - mean_notSpam
    
    temp = temp.reshape(d,1)
    #Summing up the outer product of all these temp vectors
    covariance_matrix += np.matmul(temp, np.transpose(temp))

covariance_matrix = covariance_matrix/N

covariance_matrix_inverse = np.linalg.inv(covariance_matrix)

#Constructing the terms in g(x) formula from slides (used to find posterior class probabiltiy)
term1 = np.matmul(covariance_matrix_inverse, (mean_spam-mean_notSpam))
term1 = np.transpose(term1)

term2 = np.matmul(covariance_matrix_inverse, mean_notSpam)
