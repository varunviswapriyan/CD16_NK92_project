term3 = np.matmul(covariance_matrix_inverse, mean_spam)
term3 = -0.5 * np.matmul(np.transpose(mean_spam), term3)

term4 = prob_spam/(1-prob_spam)
term4 = np.log(term4)

combined = term2+term3+term4

num_test = len(y_test)
errors = 0

#Looping through all test cases
